"""Generates libcloudcore/src/nfc_table.h: canonical compositions
base + combining mark -> precomposed character for U+00C0..U+024F.
Run from the AmiCloudCore root: python3 tools/gen-nfc-table.py"""
import unicodedata

rows = []
for cp in range(0xC0, 0x250):
    d = unicodedata.decomposition(chr(cp))
    if not d or d.startswith('<'):
        continue
    parts = [int(x, 16) for x in d.split()]
    if len(parts) != 2 or not 0x300 <= parts[1] <= 0x36F:
        continue
    if unicodedata.normalize('NFC', chr(parts[0]) + chr(parts[1])) != chr(cp):
        continue
    rows.append((parts[0], parts[1], cp))
rows.sort()
out = ['/* SPDX-License-Identifier: GPL-3.0-or-later',
       ' * Copyright (C) 2026 Ronny Krueger',
       ' *',
       " * nfc_table.h -- GENERATED by tools/gen-nfc-table.py from Python's",
       ' * unicodedata, do not edit. Canonical compositions base + combining mark',
       ' * -> precomposed character for U+00C0..U+024F (Latin-1 Supplement,',
       ' * Latin Extended-A and -B): enough for every 8-bit Latin codeset the',
       ' * Amiga uses (ISO-8859-x, AmigaPL, Windows-125x). Sorted by base, mark.',
       ' */',
       'static const unsigned short nfc_pairs[][3] = {']
out += ['    { 0x%04X, 0x%04X, 0x%04X },' % r for r in rows]
out.append('};')
open('libcloudcore/src/nfc_table.h', 'w').write('\n'.join(out) + '\n')
print(len(rows), 'Paare')
